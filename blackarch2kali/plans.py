"""Category installation plans and wrapper-script generation.

Generated shell scripts are static templates filled ONLY from repo-controlled configuration
(config/categories.yaml). No BlackArch/GitHub metadata ever reaches an executable script.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

from .models import ToolRecord
from .security.command_safety import safe_write_text

_SLUG = re.compile(r"^[a-z0-9_]{1,60}$")
_CAT_NAME = re.compile(r"^[A-Za-z0-9 /&-]{1,60}$")

SCRIPT_TEMPLATE = """#!/usr/bin/env bash
# Generated by blackarch2kali from config/categories.yaml. Contains no upstream metadata.
# Default is DRY RUN. Installation needs --confirm (and interactive approval of the plan digest).
set -euo pipefail
mode=(--dry-run)
extra=()
for arg in "$@"; do
  case "$arg" in
    --dry-run) mode=(--dry-run) ;;
    --confirm) mode=(--confirm) ;;
    --verbose|--include-derived|--json) extra+=("$arg") ;;
    --plan-digest=*) extra+=("$arg") ;;
    -h|--help) echo "usage: $0 [--dry-run|--confirm] [--plan-digest=SHA256] [--include-derived] [--verbose]"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done
exec blackarch2kali install --category {category} "${{mode[@]}}" ${{extra[@]+"${{extra[@]}}"}}
"""


def category_slug(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    if not _SLUG.fullmatch(slug):
        raise ValueError(f"invalid category name: {name!r}")
    return slug


def category_members(tools: dict[str, ToolRecord], category: str, include_derived: bool = False) -> list[tuple[ToolRecord, str]]:
    out: list[tuple[ToolRecord, str]] = []
    for t in sorted(tools.values(), key=lambda x: x.tool_name):
        if category in t.research_categories:
            out.append((t, "official"))
        elif include_derived and category in t.derived_categories:
            out.append((t, "derived"))
    return out


def category_plan(tools: dict[str, ToolRecord], category: str, include_derived: bool = False) -> dict[str, Any]:
    entries, excluded = [], []
    for t, origin in category_members(tools, category, include_derived):
        base = {"tool": t.tool_name, "membership": origin, "risk": t.security_risk, "compatibility": t.kali_compatibility}
        if t.preferred_install_method and t.install_commands:
            entries.append({**base, "method": t.preferred_install_method, "commands": t.install_commands})
        else:
            excluded.append({**base, "reason": "blocked pending review" if t.installation_methods else "no verified installation method"})
    digest = hashlib.sha256(json.dumps(entries, sort_keys=True).encode()).hexdigest()
    return {"category": category, "install": entries, "excluded": excluded, "digest": digest,
            "note": "Derived members are keyword matches, not official BlackArch categories." if include_derived else ""}


def generate_category_artifacts(tools: dict[str, ToolRecord], category_cfg: dict[str, dict[str, Any]], out_dir: Path, *, include_derived: bool = False) -> list[Path]:
    written: list[Path] = []
    cats_dir, inst_dir = out_dir / "categories", out_dir / "installers"
    for cat in sorted(category_cfg):
        if not _CAT_NAME.fullmatch(cat):
            raise ValueError(f"unsafe category name in configuration: {cat!r}")
        slug = category_slug(cat)
        plan = category_plan(tools, cat, include_derived=include_derived)
        p = cats_dir / f"{slug}.json"
        safe_write_text(p, json.dumps(plan, indent=2, sort_keys=True) + "\n")
        written.append(p)
        s = inst_dir / f"install_{slug}.sh"
        safe_write_text(s, SCRIPT_TEMPLATE.format(category=json.dumps(cat)), mode=0o755)
        written.append(s)
    return written
